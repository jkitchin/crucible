"""Walking a wiki's articles, and the aliases symlinks give them."""

import errno
import os
import stat
from pathlib import Path


def _is_article(real: Path, wiki_real: Path) -> bool:
    """Whether the walk collects the real file `real` under its own path."""
    return (real.name.endswith(".org") and real != wiki_real / "index.org"
            and real.is_file())


def wiki_article_files(wiki_dir: Path) -> list[Path]:
    """Return the authored .org articles under a wiki directory, sorted.

    The top-level wiki/index.org is generated by `crucible index` and is not
    an article, so it is excluded. An index.org in a subdirectory (e.g. a
    concept article about "index") is an ordinary article and is kept.
    Entries that are not regular files are skipped, such as the dangling
    `.#name.org` lock symlinks Emacs creates while a buffer has unsaved
    changes.

    Symlinked directories are followed (a wiki kept in Dropbox is often
    linked in), each real directory once, so a symlink loop cannot recurse
    forever. Paths are returned under `wiki_dir` as spelled, not resolved.
    A symlink to a directory inside the wiki, or to an article in it, is an
    alias of articles that already have a path, so it is skipped: otherwise
    which spelling an article got would depend on scan order. A symlink to
    a file the walk would not collect (dft.org -> drafts/dft.org.bak) is
    the article's only path, so it is kept. Entries are visited in name
    order, so the result never depends on the order scandir returns them.

    Errors are raised rather than suppressed, so an incomplete scan can never
    be mistaken for deleted articles. That is why this walks with scandir:
    rglob and os.walk skip entries whose type cannot be read. The exception
    is an entry that vanishes during the scan, which really is gone.
    """
    index_path = wiki_dir / "index.org"
    wiki_real = wiki_dir.resolve()
    org_files = []
    seen_dirs = set()
    pending = [wiki_dir]
    while pending:
        directory = pending.pop()
        try:
            dir_stat = directory.stat()
        except FileNotFoundError:
            continue
        dir_key = (dir_stat.st_dev, dir_stat.st_ino)
        if dir_key in seen_dirs:
            continue
        seen_dirs.add(dir_key)
        try:
            with os.scandir(directory) as it:
                entries = sorted(it, key=lambda e: e.name)
        except FileNotFoundError:
            continue
        # Pushed in reverse so the stack visits directories in name order.
        subdirs = []
        for entry in entries:
            path = Path(entry.path)
            try:
                mode = entry.stat(follow_symlinks=False).st_mode
                if stat.S_ISLNK(mode):
                    # A dangling link, such as an Emacs `.#name.org` lock,
                    # or a link to itself is skipped. A link to a directory
                    # or an article in the wiki is an alias of articles
                    # indexed under their own path (dft.org ->
                    # density-functional-theory.org), so it is skipped too;
                    # links through it resolve to them (wiki_alias_of).
                    # Other links are followed.
                    try:
                        mode = entry.stat(follow_symlinks=True).st_mode
                    except OSError as exc:
                        if isinstance(exc, FileNotFoundError) or exc.errno == errno.ELOOP:
                            continue
                        raise
                    real = path.resolve()
                    if real.is_relative_to(wiki_real) and (
                        stat.S_ISDIR(mode) or _is_article(real, wiki_real)
                    ):
                        continue
            except FileNotFoundError:
                continue
            if stat.S_ISDIR(mode):
                subdirs.append(path)
            elif (
                entry.name.endswith(".org")
                and path != index_path
                and stat.S_ISREG(mode)
            ):
                org_files.append(path)
        pending.extend(reversed(subdirs))
    return sorted(org_files)


def wiki_alias_of(wiki_dir: Path, target: Path) -> Path | None:
    """The path the walk indexes `target` under, when a symlink makes it an alias.

    wiki_article_files skips symlinks to directories or articles inside the
    wiki, so a path through one ([[file:dft.org]] with dft.org a link, or
    [[file:topics/basis.org]] with topics a link) names an article indexed
    under its real path. Returns that path, spelled under `wiki_dir`, or
    None when `target` is not such an alias.
    """
    try:
        wiki_real = wiki_dir.resolve()
        real = Path(os.path.abspath(target)).resolve()
        if not (real.is_relative_to(wiki_real) and _is_article(real, wiki_real)):
            return None
    except (OSError, RuntimeError):
        return None
    mapped = wiki_dir / real.relative_to(wiki_real)
    return mapped if mapped != target else None
